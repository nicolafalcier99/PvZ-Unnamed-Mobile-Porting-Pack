"""Generates src/Mod/GbkTable.inc: GB18030 two-byte -> Unicode table (lead 0x81-0xFE, trail 0x40-0xFE).
0 = not a valid two-byte code. Data comes from Python's own gb18030 codec. Run: python3 -I tools/gen_gbk_table.py"""
import os
out = []
for lead in range(0x81, 0xFF):
    for trail in range(0x40, 0xFF):
        cp = 0
        if trail != 0x7F:
            try:
                ch = bytes([lead, trail]).decode('gb18030')
                if len(ch) == 1 and ord(ch) <= 0xFFFF:
                    cp = ord(ch)
            except UnicodeDecodeError:
                pass
        out.append(cp)
path = os.path.join(os.path.dirname(__file__), '..', 'src', 'Mod', 'GbkTable.inc')
with open(path, 'w') as f:
    f.write('// Generated by tools/gen_gbk_table.py (Python gb18030 codec). Do not edit.\n')
    f.write('// Index = (lead - 0x81) * 191 + (trail - 0x40); 0 = invalid.\n')
    for i in range(0, len(out), 16):
        f.write(','.join(str(v) for v in out[i:i+16]) + ',\n')
print(len(out), 'entries', sum(1 for v in out if v), 'valid')
